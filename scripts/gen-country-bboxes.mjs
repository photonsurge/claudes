#!/usr/bin/env node
/**
 * Bake a bbox for every country from the Natural Earth admin-0 GeoJSON that
 * already ships with the app, into a generated TS module the region picker's
 * "All countries" dropdown reads.
 *
 * Framing, not geography: for each country we take the bbox of its LARGEST
 * outer ring (by |shoelace area|), i.e. the main landmass. That deliberately
 * drops overseas territories and far-flung islands — so France frames on
 * metropolitan France (not French Guiana), the USA on the CONUS (not the
 * Aleutians crossing the antimeridian), etc. — which is what you want when the
 * camera flies to a country.
 *
 *   node scripts/gen-country-bboxes.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "public/public/data/countries.geojson");
const OUT = join(root, "shared/src/countries.generated.ts");

/** |shoelace| area of a [lng,lat][] ring — good enough to rank ring sizes. */
function ringArea(ring) {
  let a = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    a += ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
  }
  return Math.abs(a) / 2;
}

function ringBbox(ring) {
  let w = 180, s = 90, e = -180, n = -90;
  for (const [lng, lat] of ring) {
    if (lng < w) w = lng;
    if (lng > e) e = lng;
    if (lat < s) s = lat;
    if (lat > n) n = lat;
  }
  return [round(w), round(s), round(e), round(n)];
}

const round = (x) => Math.round(x * 100) / 100;

/** Outer rings across Polygon / MultiPolygon geometry. */
function outerRings(geom) {
  if (!geom) return [];
  if (geom.type === "Polygon") return [geom.coordinates[0]];
  if (geom.type === "MultiPolygon") return geom.coordinates.map((poly) => poly[0]);
  return [];
}

const slug = (s) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const geo = JSON.parse(readFileSync(SRC, "utf8"));
const byId = new Map();

for (const f of geo.features) {
  const p = f.properties || {};
  const name = p.admin || p.name || p.name_long;
  if (!name) continue;
  // Skip Antarctica — a full-width ring that frames to the whole globe.
  if (/antarctica/i.test(name)) continue;

  let biggest = null;
  let biggestArea = -1;
  for (const ring of outerRings(f.geometry)) {
    const a = ringArea(ring);
    if (a > biggestArea) {
      biggestArea = a;
      biggest = ring;
    }
  }
  if (!biggest) continue;

  const iso = typeof p.iso_a2 === "string" && /^[A-Za-z]{2}$/.test(p.iso_a2) ? p.iso_a2.toLowerCase() : null;
  const id = iso || slug(name);
  const entry = { id, name, bbox: ringBbox(biggest), _area: biggestArea };

  // On an id collision (e.g. a country split into several admin-0 features)
  // keep the one whose main ring is bigger — the true mainland.
  const prev = byId.get(id);
  if (!prev || entry._area > prev._area) byId.set(id, entry);
}

const rows = [...byId.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((c) => `  { id: ${JSON.stringify(c.id)}, name: ${JSON.stringify(c.name)}, bbox: [${c.bbox.join(", ")}] },`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-country-bboxes.mjs — do not edit by hand.
// Source: public/public/data/countries.geojson (Natural Earth admin-0).
// bbox is the main-landmass framing box [west, south, east, north].
export interface iCountryBbox {
  /** ISO 3166-1 alpha-2 (lowercased) where available, else a name slug. */
  id: string;
  name: string;
  bbox: [number, number, number, number];
}

export const COUNTRY_BBOXES: iCountryBbox[] = [
${rows}
];
`;

writeFileSync(OUT, out);
console.log(`Wrote ${byId.size} countries → ${OUT}`);
